export type FinanceStatementModalProps = {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  studentId?: number | string | null;
  parentToken?: string | null;
  studentLabel?: string;
};

const FinanceStatementModal: React.FC<FinanceStatementModalProps> = ({
  open,
  onOpenChange,
  studentId,
  parentToken,
  studentLabel,
}) => {
  const [loading, setLoading] = useState(false);
  const [statement, setStatement] = useState<StudentFinanceStatement | null>(null);
  const [logoUrl, setLogoUrl] = useState<string | null>(null);
  const previewRef = useRef<HTMLDivElement>(null);

  const loadStatement = useCallback(async () => {
    const authToken = parentToken;
    setLoading(true);
    setStatement(null);
    try {
      let data: StudentFinanceStatement;
      if (authToken) {
        data = await fetchParentFinanceStatement(authToken);
      } else if (studentId != null) {
        data = await fetchStudentFinanceStatement(studentId);
      } else {
        throw new Error('No student selected');
      }
      if (parentToken !== authToken) return;
      setStatement(data);
      setLogoUrl(resolveLogoUrl(data.header.logoUrl));
    } catch (e: unknown) {
      toast({
        title: 'Could not load statement',
        description: (e as Error).message || 'Please try again.',
        variant: 'destructive',
      });
      onOpenChange(false);
    } finally {
      setLoading(false);
    }
  }, [studentId, parentToken, onOpenChange]);

  useEffect(() => {
    if (open) void loadStatement();
    else {
      setStatement(null);
      setLogoUrl(null);
    }
  }, [open, loadStatement]);

  const handlePrint = () => {
    if (!previewRef.current) return;
    printFinanceStatementPreview(previewRef.current);
  };

  const title = studentLabel || statement?.header.studentName || 'Finance Statement';

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-4xl max-h-[90vh] overflow-hidden flex flex-col">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2">
              <FileText className="h-5 w-5" />
              Finance Statement — {title}
            </DialogTitle>
            <DialogDescription>
              Review the full financial history before printing.
            </DialogDescription>
          </DialogHeader>

          <div className="flex-1 overflow-y-auto border rounded-md p-4 bg-white">
            {loading ? (
              <div className="flex items-center justify-center py-16 text-muted-foreground gap-2">
                <Loader2 className="h-5 w-5 animate-spin" />
                Loading statement…
              </div>
            ) : statement ? (
              <FinanceStatementPreview ref={previewRef} statement={statement} logoUrl={logoUrl} />
            ) : null}
          </div>

          <DialogFooter className="fs-no-print gap-2 sm:gap-2">
            <Button type="button" variant="outline" onClick={() => onOpenChange(false)}>
              Close
            </Button>
            <Button type="button" onClick={handlePrint} disabled={!statement || loading}>
              <Printer className="h-4 w-4 mr-1" />
              Print / Save as PDF
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
  );
};

export default FinanceStatementModal;
