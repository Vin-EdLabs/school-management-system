const EMPTY = '—';
const MARGIN = 14;
const SECTION_GAP = 6;

type PdfField = { label: string; value: string };
type PdfSection = { title: string; fields: PdfField[] };

const TABLE_THEME = {
  theme: 'grid' as const,
  headStyles: {
    fillColor: [242, 242, 242] as [number, number, number],
    textColor: 34,
    halign: 'left' as const,
    fontStyle: 'bold' as const,
  },
  bodyStyles: { valign: 'top' as const, textColor: 55 },
  styles: {
    font: 'times',
    fontSize: 9,
    cellPadding: 3,
    textColor: 55,
    lineColor: [180, 180, 180] as [number, number, number],
    lineWidth: 0.15,
  },
  margin: { left: MARGIN, right: MARGIN },
  tableLineColor: [180, 180, 180] as [number, number, number],
  tableLineWidth: 0.15,
  columnStyles: {
    0: { cellWidth: 52, fontStyle: 'bold' as const, textColor: [75, 75, 75] as [number, number, number] },
    1: { cellWidth: 'auto' as const },
  },
};

function display(v: unknown): string {
  if (v == null) return EMPTY;
  if (typeof v === 'boolean') return v ? 'Yes' : 'No';
  const s = String(v).trim();
  return s || EMPTY;
}

function profileFilename(fullName: string): string {
  const safe = fullName.replace(/[^\w\s-]/g, '').trim().replace(/\s+/g, '_');
  const d = new Date();
  const ymd = `${d.getFullYear()}${String(d.getMonth() + 1).padStart(2, '0')}${String(d.getDate()).padStart(2, '0')}`;
  return `Profile_${safe || 'Staff'}_${ymd}.pdf`;
}

function footerDateTime(): string {
  return new Date().toLocaleString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
    hour12: true,
  });
}

async function resolveAndLoadLogo(logoUrl?: string | null): Promise<string | null> {
  const resolved = resolveLogoUrl(logoUrl ?? null);
  if (!resolved) return null;
  return loadImageDataUrl(resolved);
}

function drawSectionDivider(doc: jsPDF, y: number): number {
  const pageW = doc.internal.pageSize.getWidth();
  doc.setDrawColor(200, 200, 200);
  doc.setLineWidth(0.2);
  doc.line(MARGIN, y, pageW - MARGIN, y);
  return y + SECTION_GAP;
}

function drawFooter(doc: jsPDF) {
  const total = doc.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    doc.setPage(i);
    const pageW = doc.internal.pageSize.getWidth();
    const pageH = doc.internal.pageSize.getHeight();
    doc.setDrawColor(210, 210, 210);
    doc.setLineWidth(0.2);
    doc.line(MARGIN, pageH - 14, pageW - MARGIN, pageH - 14);
    doc.setFont('times', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(110, 110, 110);
    doc.text('Generated by ScholarNerve', MARGIN, pageH - 8);
    doc.text(`Page ${i} of ${total}`, pageW / 2, pageH - 8, { align: 'center' });
    doc.text(footerDateTime(), pageW - MARGIN, pageH - 8, { align: 'right' });
  }
}

function drawProfileSection(doc: jsPDF, startY: number, section: PdfSection, isFirst: boolean): number {
  let y = startY;
  if (!isFirst) {
    y = drawSectionDivider(doc, y);
  }

  autoTable(doc, {
    startY: y,
    head: [[{ content: section.title, colSpan: 2 }]],
    body: section.fields.map((field) => [field.label, field.value]),
    ...TABLE_THEME,
  });

  return pdfLastTableY(doc) + 4;
}

function buildProfileDoc(
  schoolName: string,
  reportTitle: string,
  metaLines: string[],
  logoDataUrl: string | null,
  sections: PdfSection[]
): jsPDF {
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation: 'portrait' });
  let y = drawClassicSchoolPdfHeader(doc, {
    schoolName,
    logoDataUrl,
    reportTitle,
    metaLines,
    margin: MARGIN,
  });

  sections.forEach((section, index) => {
    y = drawProfileSection(doc, y, section, index === 0);
  });

  drawFooter(doc);
  return doc;
}

export function formatSubjectClassesForPdf(data: TeacherSubjectClassesResponse | null | undefined): string {
  if (!data?.by_subject?.length) return EMPTY;
  return data.by_subject
    .map((s) => {
      const classes = (s.classes || []).map((c) => c.class_name).filter(Boolean).join(', ');
      return classes ? `${s.subject_name}: ${classes}` : s.subject_name;
    })
    .join('; ');
}

function moneyGhs(amount: number | string | null | undefined): string {
  const n = typeof amount === 'number' ? amount : parseFloat(String(amount || ''));
  if (!n || Number.isNaN(n) || n <= 0) return EMPTY;
  return `GHS ${n.toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

export async function downloadTeacherProfilePdf(
  teacher: Teacher,
  subjectClasses: TeacherSubjectClassesResponse | null | undefined,
  schoolName: string,
  logoUrl?: string | null
): Promise<void> {
  const logoDataUrl = await resolveAndLoadLogo(logoUrl);
  const generatedAt = new Date();

  const sections: PdfSection[] = [
    {
      title: 'Personal Details',
      fields: [
        { label: 'Staff ID', value: display(teacher.staffId) },
        { label: 'Full Name', value: display(teacher.fullName) },
        { label: 'Gender', value: display(teacher.gender) },
        { label: 'Date of Birth', value: teacher.dateOfBirth ? formatDisplayDate(teacher.dateOfBirth) : EMPTY },
        { label: 'Phone Number', value: display(teacher.phoneNumber) },
        { label: 'Email Address', value: display(teacher.email) },
        { label: 'Address', value: display(teacher.address) },
        { label: 'Qualification', value: display(teacher.qualification) },
        { label: 'Specialization', value: display(teacher.specialization) },
      ],
    },
    {
      title: 'Role',
      fields: [
        { label: 'Position', value: display(teacher.position) },
        { label: 'Department', value: display(teacher.department) },
      ],
    },
    {
      title: 'Teaching Assignments',
      fields: [{ label: 'Subject & Class', value: formatSubjectClassesForPdf(subjectClasses) }],
    },
    {
      title: 'Employment',
      fields: [
        { label: 'Employment Date', value: teacher.employmentDate ? formatDisplayDate(teacher.employmentDate) : EMPTY },
        { label: 'Passport Photo', value: teacher.hasPassportPhoto ? 'Uploaded' : EMPTY },
        { label: 'Monthly Salary', value: moneyGhs(teacher.monthlySalary) },
        { label: 'Notes', value: display(teacher.notes) },
      ],
    },
    {
      title: 'Emergency Contact',
      fields: [
        { label: 'Name', value: display(teacher.emergencyContactName) },
        { label: 'Relationship', value: display(teacher.emergencyContactRelationship) },
        { label: 'Phone', value: display(teacher.emergencyContactPhone) },
      ],
    },
    {
      title: 'Bank Details',
      fields: [
        { label: 'Bank', value: display(teacher.bankName) },
        { label: 'Account Name', value: display(teacher.bankAccountName) },
        { label: 'Account Number', value: display(teacher.bankAccountNumber) },
        { label: 'Branch', value: display(teacher.bankBranch) },
      ],
    },
  ];

  const doc = buildProfileDoc(
    schoolName,
    'Teacher Profile',
    [
      `Staff: ${display(teacher.fullName)}`,
      `Staff ID: ${display(teacher.staffId)}`,
      `Generated: ${generatedAt.toLocaleDateString()} ${generatedAt.toLocaleTimeString()}`,
    ],
    logoDataUrl,
    sections
  );

  doc.save(profileFilename(teacher.fullName));

  try {
    await apiService.post(`/teachers/${teacher.id}/profile-pdf-audit`, {});
  } catch {
    /* audit best-effort */
  }
}

